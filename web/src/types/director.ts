export type DirectorVector = [number, number, number];
export type DirectorKind = "person" | "box" | "sphere" | "cylinder" | "cone" | "torus" | "plane" | "chair" | "table" | "sofa" | "bed" | "door" | "window" | "tree" | "car";
export type DirectorJoint = "torso" | "head" | "leftArm" | "leftElbow" | "leftWrist" | "rightArm" | "rightElbow" | "rightWrist" | "leftLeg" | "leftKnee" | "leftAnkle" | "rightLeg" | "rightKnee" | "rightAnkle";
export type DirectorOutput = "color" | "depth" | "outline" | "mask" | "normal" | "transparent";
export type DirectorPose = "stand" | "walk" | "sit" | "reach" | "wave" | "crouch";
export type DirectorAppearance = { skin?: string; hair?: string; bottom?: string; shoes?: string; hairStyle?: "short" | "long" | "none" };
export type DirectorObject = {
    id: string;
    name: string;
    kind: DirectorKind;
    pose: DirectorPose;
    position: DirectorVector;
    rotation: DirectorVector;
    scale: DirectorVector;
    color: string;
    visible?: boolean;
    locked?: boolean;
    joints?: Partial<Record<DirectorJoint, DirectorVector>>;
    roughness?: number;
    metalness?: number;
    appearance?: DirectorAppearance;
};
export type DirectorCamera = { position: DirectorVector; target: DirectorVector; lens: number; roll?: number };
export type DirectorStage = Pick<DirectorScene, "objects" | "light" | "background" | "floor" | "floorVisible">;
export type DirectorFrame = DirectorStage & { camera: DirectorCamera };
export type DirectorKeyframe = { id: string; time: number; frame: DirectorFrame };
export type DirectorShot = {
    id: string; name: string; camera: DirectorCamera; width: number; height: number; note?: string;
    stage?: DirectorStage;
    duration?: number;
    easing?: "linear" | "smooth" | "hold";
    cameraPath?: "linear" | "orbit";
    keyframes?: DirectorKeyframe[];
    dialogue?: string;
    sound?: string;
};
export type DirectorScene = {
    schema: 1;
    objects: DirectorObject[];
    camera: DirectorCamera;
    light: { azimuth: number; elevation: number; intensity: number; color?: string; ambient?: number; fill?: number; rim?: number; shadows?: boolean };
    background: string;
    floor: string;
    width: number;
    height: number;
    grid: boolean;
    guide?: "none" | "thirds" | "center";
    shots?: DirectorShot[];
    floorVisible?: boolean;
    note?: string;
    safeFrame?: boolean;
    motionPaths?: boolean;
};
export type DirectorVideoPrompt = {
    summary: string; prompt: string; negativePrompt?: string;
    shots: {start:number;end:number;description:string;camera:string;action:string;prompt:string}[];
    uncertainties?: string[];
};
export type DirectorAssistantSettings = {mode?: "scene"|"animation"|"video";model?:string;prompt?:string;sourceIds?:string[];reverse?:DirectorVideoPrompt;reverseSource?:{name:string;duration:number;times:number[]}};
